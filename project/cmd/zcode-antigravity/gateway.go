func (a *app) gatewayURL(port int) string {
	return fmt.Sprintf("http://127.0.0.1:%d", port)
}

func httpClient(timeout time.Duration) *http.Client {
	return &http.Client{
		Timeout: timeout,
		Transport: &http.Transport{
			Proxy:               http.ProxyFromEnvironment,
			DisableCompression:  false,
			MaxIdleConns:        4,
			IdleConnTimeout:     30 * time.Second,
			TLSHandshakeTimeout: 5 * time.Second,
		},
	}
}

func (a *app) probeGateway(port int) error {
	client := httpClient(1500 * time.Millisecond)
	rootResp, err := client.Get(a.gatewayURL(port) + "/")
	if err != nil {
		return err
	}
	defer rootResp.Body.Close()
	if rootResp.StatusCode != http.StatusOK {
		return fmt.Errorf("根端点返回 HTTP %d", rootResp.StatusCode)
	}
	var root struct {
		Message string `json:"message"`
	}
	if err := json.NewDecoder(io.LimitReader(rootResp.Body, 64<<10)).Decode(&root); err != nil {
		return fmt.Errorf("根端点不是预期 JSON: %w", err)
	}
	if root.Message != "CLI Proxy API Server" {
		return fmt.Errorf("端口上的服务不是 CLI Proxy API")
	}
	healthResp, err := client.Get(a.gatewayURL(port) + "/healthz")
	if err != nil {
		return err
	}
	defer healthResp.Body.Close()
	if healthResp.StatusCode != http.StatusOK {
		return fmt.Errorf("健康检查返回 HTTP %d", healthResp.StatusCode)
	}
	return nil
}

func (a *app) fetchModels(port int) ([]modelInfo, error) {
	req, err := http.NewRequest(http.MethodGet, a.gatewayURL(port)+"/v1/models", nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("x-api-key", a.apiKey)
	req.Header.Set("Authorization", "Bearer "+a.apiKey)
	req.Header.Set("anthropic-version", "2023-06-01")
	req.Header.Set("User-Agent", "ZCode-Antigravity-Bridge/"+version)
	resp, err := httpClient(5 * time.Second).Do(req)
	if err != nil {
		return nil, fmt.Errorf("读取模型列表: %w", err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("模型列表返回 HTTP %d: %s", resp.StatusCode, compactText(body, 240))
	}
	var payload modelsResponse
	if err := json.Unmarshal(body, &payload); err != nil {
		return nil, fmt.Errorf("模型列表不是预期 JSON: %w", err)
	}
	seen := make(map[string]bool)
	models := make([]modelInfo, 0, len(payload.Data))
	for _, model := range payload.Data {
		model.ID = strings.TrimSpace(model.ID)
		model.DisplayName = strings.TrimSpace(model.DisplayName)
		if model.ID == "" || seen[model.ID] {
			continue
		}
		seen[model.ID] = true
		models = append(models, model)
	}
	sort.Slice(models, func(i, j int) bool { return models[i].ID < models[j].ID })
	return models, nil
}

func compactText(raw []byte, max int) string {
	value := strings.Join(strings.Fields(string(raw)), " ")
	if len(value) > max {
		return value[:max] + "..."
	}
	return value
}

func isPortFree(port int) bool {
	listener, err := net.Listen("tcp4", fmt.Sprintf("127.0.0.1:%d", port))
	if err != nil {
		return false
	}
	_ = listener.Close()
	return true
}

func chooseFreePort(start, end int) (int, error) {
	for candidate := start; candidate <= end; candidate++ {
		if isPortFree(candidate) {
			return candidate, nil
		}
	}
	return 0, fmt.Errorf("端口 %d-%d 全部被占用", start, end)
}

func (a *app) chooseGatewayPort() (port int, reuse bool, err error) {
	cfg := a.currentSettings()
	current, stateErr := a.loadState()
	if stateErr != nil {
		return 0, false, stateErr
	}
	candidates := make([]int, 0, cfg.PortScanEnd-cfg.PreferredPort+2)
	if current.Port >= cfg.PreferredPort && current.Port <= cfg.PortScanEnd {
		candidates = append(candidates, current.Port)
	}
	for candidate := cfg.PreferredPort; candidate <= cfg.PortScanEnd; candidate++ {
		candidates = append(candidates, candidate)
	}
	seen := make(map[int]bool)
	occupied := make([]string, 0, 4)
	for _, candidate := range candidates {
		if seen[candidate] {
			continue
		}
		seen[candidate] = true
		if err := a.probeGateway(candidate); err == nil {
			if _, authErr := a.fetchModels(candidate); authErr == nil {
				return candidate, true, nil
			}
		}
		if isPortFree(candidate) {
			return candidate, false, nil
		}
		if len(occupied) < 4 {
			occupied = append(occupied, fmt.Sprintf("%d (%s)", candidate, describePortOwner(candidate)))
		}
	}
	return 0, false, fmt.Errorf("端口 %d-%d 全部被占用；示例: %s", cfg.PreferredPort, cfg.PortScanEnd, strings.Join(occupied, ", "))
}

func (a *app) startAndConfigure() (returnErr error) {
	cfg := a.currentSettings()
	if _, err := os.Stat(a.paths.Backend); err != nil {
		return fmt.Errorf("缺少网关程序 %s: %w", a.paths.Backend, err)
	}
	accounts, errAccounts := countProviderAccounts(a.paths.AuthDir)
	if errAccounts != nil {
		return errAccounts
	}
	if accounts.total() == 0 {
		return fmt.Errorf("没有有效账号；请先登录 Antigravity 或 Grok")
	}
	startedPID := 0
	configurationComplete := false
	defer func() {
		if returnErr == nil || startedPID <= 0 || configurationComplete {
			return
		}
		if errStop := terminateOwnedProcess(startedPID, a.paths.Backend); errStop != nil {
			returnErr = errors.Join(returnErr, fmt.Errorf("回收启动失败后的网关: %w", errStop))
			return
		}
		current, errState := a.loadState()
		if errState == nil && current.PID == startedPID {
			current.PID = 0
			if errSave := a.saveState(current); errSave != nil {
				returnErr = errors.Join(returnErr, fmt.Errorf("清理失败启动状态: %w", errSave))
			}
		}
	}()
	port, reuse, err := a.chooseGatewayPort()
	if err != nil {
		return err
	}
	if reuse {
		var managementProbe managementAuthFiles
		if errManagement := a.managementJSON(port, http.MethodGet, "/v0/management/auth-files", nil, &managementProbe); errManagement != nil {
			current, errCurrent := a.loadState()
			if errCurrent != nil || current.PID <= 0 || strings.TrimSpace(current.BackendPath) == "" {
				return fmt.Errorf("正在运行的旧网关不支持额度界面，且无法验证其进程所有权；请用控制中心安全停止后重试")
			}
			if errStop := terminateOwnedProcess(current.PID, current.BackendPath); errStop != nil {
				return fmt.Errorf("升级额度接口前停止旧网关: %w", errStop)
			}
			deadline := time.Now().Add(5 * time.Second)
			for !isPortFree(port) && time.Now().Before(deadline) {
				time.Sleep(100 * time.Millisecond)
			}
			if !isPortFree(port) {
				port, err = chooseFreePort(cfg.PreferredPort, cfg.PortScanEnd)
				if err != nil {
					return err
				}
			}
			reuse = false
			current.PID = 0
			_ = a.saveState(current)
		}
	}
	if reuse {
		fmt.Printf("已复用正在运行的本地网关: %s\n", a.gatewayURL(port))
	} else {
		if port != cfg.PreferredPort {
			fmt.Printf("默认端口 %d 已占用，自动改用 %d。\n", cfg.PreferredPort, port)
		}
		if err := a.writeBackendConfig(port); err != nil {
			return fmt.Errorf("写入网关配置: %w", err)
		}
		if err := rotateManagedFile(a.paths.ConsoleLog, 10<<20, 3); err != nil {
			return fmt.Errorf("轮转网关控制台日志: %w", err)
		}
		pid, err := launchDetached(a.paths.Backend, []string{"-config", a.paths.Config, "-local-model"}, a.paths.Data, a.paths.ConsoleLog)
		if err != nil {
			return fmt.Errorf("启动网关: %w", err)
		}
		startedPID = pid
		if err := a.waitForGateway(port, 20*time.Second); err != nil {
			_ = terminateOwnedProcess(pid, a.paths.Backend)
			return fmt.Errorf("网关未就绪，已停止刚启动的进程；请查看 %s: %w", a.paths.ConsoleLog, err)
		}
		current := state{
			Port:           port,
			PID:            pid,
			BackendPath:    a.paths.Backend,
			StartedAt:      a.now().UTC(),
			Launcher:       version,
			LastHealthTime: a.now().UTC(),
		}
		if err := a.saveState(current); err != nil {
			_ = terminateOwnedProcess(pid, a.paths.Backend)
			return fmt.Errorf("保存状态失败，已停止网关: %w", err)
		}
		fmt.Printf("网关已启动: %s (PID %d)\n", a.gatewayURL(port), pid)
	}

	fmt.Println("正在等待模型目录加载（网络异常时最多约 35 秒）...")
	catalog, err := a.waitForModels(port, 35*time.Second)
	if err != nil {
		return err
	}
	models, warnings := selectAvailableAgentModels(catalog,
		accounts.Antigravity > 0,
		accounts.XAI > 0 && cfg.EnableGrokModels,
		accounts.Antigravity > 0 && cfg.EnableOtherModels,
	)
	for _, warning := range warnings {
		fmt.Printf("模型提供商警告: %v\n", warning)
	}
	if len(models) == 0 {
		return fmt.Errorf("没有可同步的 Gemini / Claude / Grok 文本模型: %w", errors.Join(warnings...))
	}
	backup, changed, err := a.configureZCodeWithAccess(port, models, cfg.EnableGrokModels, cfg.EnableOtherModels)
	if err != nil {
		return err
	}
	current, _ := a.loadState()
	current.Port = port
	current.ZCodeConfig = a.paths.ZCodeConfig
	current.Models = modelIDs(models)
	current.LastHealthTime = a.now().UTC()
	current.Launcher = version
	if backup != "" {
		current.ZCodeBackup = backup
	}
	configurationComplete = true
	if err := a.saveState(current); err != nil {
		return fmt.Errorf("保存最终状态: %w", err)
	}
	if changed {
		fmt.Printf("ZCode Provider 已写入并备份原配置: %s\n", backup)
		fmt.Printf("请完全退出并重新打开 ZCode，然后选择 %s 模型。\n", providerName)
	} else {
		fmt.Println("ZCode Provider 已是最新配置。")
	}
	fmt.Printf("已同步 %d 个模型。\n", len(models))
	return nil
}

func (a *app) waitForGateway(port int, timeout time.Duration) error {
	deadline := time.Now().Add(timeout)
	var lastErr error
	for time.Now().Before(deadline) {
		if err := a.probeGateway(port); err == nil {
			return nil
		} else {
			lastErr = err
		}
		time.Sleep(250 * time.Millisecond)
	}
	if lastErr == nil {
		lastErr = errors.New("等待超时")
	}
	return lastErr
}

func (a *app) waitForModels(port int, timeout time.Duration) ([]modelInfo, error) {
	deadline := time.Now().Add(timeout)
	var lastErr error
	for {
		models, err := a.fetchModels(port)
		if err == nil && len(models) > 0 {
			return models, nil
		}
		if err != nil {
			lastErr = err
		}
		if time.Now().After(deadline) {
			if lastErr != nil {
				return nil, lastErr
			}
			return nil, fmt.Errorf("模型目录在 %s 内仍为空；请检查账号、代理和 %s", timeout.Round(time.Second), a.paths.ConsoleLog)
		}
		time.Sleep(time.Second)
	}
}

func (a *app) login() error {
	cfg := a.currentSettings()
	if _, err := os.Stat(a.paths.Backend); err != nil {
		return fmt.Errorf("缺少网关程序 %s: %w", a.paths.Backend, err)
	}
	port := cfg.PreferredPort
	if current, err := a.loadState(); err == nil && current.Port >= cfg.PreferredPort && current.Port <= cfg.PortScanEnd {
		port = current.Port
	}
	if err := a.writeBackendConfig(port); err != nil {
		return fmt.Errorf("准备登录配置: %w", err)
	}
	callbackPort, err := chooseFreePort(cfg.CallbackPreferredPort, cfg.CallbackScanEnd)
	if err != nil {
		return fmt.Errorf("OAuth 回调端口 %d-%d 全部被占用", cfg.CallbackPreferredPort, cfg.CallbackScanEnd)
	}
	if callbackPort != cfg.CallbackPreferredPort {
		fmt.Printf("OAuth 默认回调端口 %d 已占用，自动改用 %d。\n", cfg.CallbackPreferredPort, callbackPort)
	}
	fmt.Println("浏览器将打开 Google 登录页。授权完成前请不要关闭此窗口。")
	started := a.now()
	var captured bytes.Buffer
	cmd := exec.Command(a.paths.Backend, "-config", a.paths.Config, "-antigravity-login", "-oauth-callback-port", strconv.Itoa(callbackPort))
	cmd.Dir = a.paths.Data
	prepareChildProcess(cmd)
	if browserPath := preferredBrowserExecutable(); browserPath != "" {
		cmd.Env = append(os.Environ(), "CLIPROXY_BROWSER="+browserPath)
	}
	if a.guiMode {
		// A GUI launch may have no valid console handles. OAuth still opens the browser,
		// while all child output is
		// retained in memory for the same explicit success check below.
		cmd.Stdout = &captured
		cmd.Stderr = &captured
	} else {
		cmd.Stdin = os.Stdin
		cmd.Stdout = io.MultiWriter(os.Stdout, &captured)
		cmd.Stderr = io.MultiWriter(os.Stderr, &captured)
	}
	if err := cmd.Run(); err != nil {
		if friendlyErr := antigravityLoginFailure(captured.String()); friendlyErr != nil {
			return friendlyErr
		}
		return fmt.Errorf("OAuth 登录进程失败: %w", err)
	}
	if friendlyErr := antigravityLoginFailure(captured.String()); friendlyErr != nil {
		return friendlyErr
	}
	if !strings.Contains(captured.String(), "Antigravity authentication successful!") {
		return fmt.Errorf("登录程序未确认成功，请检查上方输出")
	}
	if !hasRecentAntigravityAccount(a.paths.AuthDir, started.Add(-2*time.Second)) {
		return fmt.Errorf("登录程序报告成功，但未找到新凭据文件；不会继续覆盖 ZCode 配置")
	}
	fmt.Printf("Antigravity 登录成功。凭据只保存在当前用户目录: %s\n", a.paths.AuthDir)
	return nil
}

func antigravityLoginFailure(output string) error {
	lower := strings.ToLower(output)
	if strings.Contains(lower, "authentication timed out") || strings.Contains(lower, "oauth flow timed out") {
		return errors.New("Google OAuth 授权页已超时；请重新点击登录，并在新打开的页面中完成授权")
	}
	return nil
}

type xaiDeviceAuthorization struct {
	UserCode        string `json:"userCode"`
	VerificationURL string `json:"verificationURL"`
}

type loginOutputCapture struct {
	mu       sync.Mutex
	buffer   bytes.Buffer
	onUpdate func(string)
}

func (capture *loginOutputCapture) Write(payload []byte) (int, error) {
	capture.mu.Lock()
	written, errWrite := capture.buffer.Write(payload)
	snapshot := capture.buffer.String()
	capture.mu.Unlock()
	if capture.onUpdate != nil {
		capture.onUpdate(snapshot)
	}
	return written, errWrite
}

func (capture *loginOutputCapture) String() string {
	capture.mu.Lock()
	defer capture.mu.Unlock()
	return capture.buffer.String()
}

func parseXAIDeviceAuthorization(output string) (xaiDeviceAuthorization, bool) {
	var result xaiDeviceAuthorization
	for _, rawLine := range strings.Split(strings.ReplaceAll(output, "\r\n", "\n"), "\n") {
		line := strings.TrimSpace(rawLine)
		if strings.HasPrefix(line, "Then enter this code:") {
			result.UserCode = strings.TrimSpace(strings.TrimPrefix(line, "Then enter this code:"))
			continue
		}
		if strings.HasPrefix(line, "https://") {
			parsed, errURL := url.Parse(line)
			if errURL == nil && parsed.Scheme == "https" && strings.EqualFold(parsed.Hostname(), "accounts.x.ai") {
				result.VerificationURL = line
			}
		}
	}
	if result.UserCode == "" || result.VerificationURL == "" {
		return xaiDeviceAuthorization{}, false
	}
	if len(result.UserCode) > 32 || strings.IndexFunc(result.UserCode, func(value rune) bool {
		return !(value == '-' || value >= '0' && value <= '9' || value >= 'A' && value <= 'Z')
	}) >= 0 {
		return xaiDeviceAuthorization{}, false
	}
	return result, true
}

