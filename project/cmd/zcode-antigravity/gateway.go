type smokeAudit struct {
	Timestamp      time.Time `json:"timestamp"`
	RequestedModel string    `json:"requestedModel"`
	ResponseModel  string    `json:"responseModel,omitempty"`
	ResponseID     string    `json:"responseID,omitempty"`
	OutputText     string    `json:"outputText"`
}

const smokeExpectedOutput = "ZCODE_SMOKE_OK"

func (a *app) smokeModel(model string) error {
	model = strings.TrimSpace(model)
	if model == "" {
		return fmt.Errorf("模型 ID 不能为空")
	}
	current, errState := a.loadState()
	if errState != nil {
		return errState
	}
	if current.Port <= 0 {
		return fmt.Errorf("网关尚未启动")
	}
	if err := a.probeGateway(current.Port); err != nil {
		return fmt.Errorf("网关未运行: %w", err)
	}
	models, errModels := a.fetchModels(current.Port)
	if errModels != nil {
		return errModels
	}
	found := false
	var selected modelInfo
	for _, available := range models {
		if available.ID == model {
			found = true
			selected = available
			break
		}
	}
	if !found {
		return fmt.Errorf("模型目录中不存在精确 ID %q", model)
	}
	if !isManagedAgentModel(selected) {
		return fmt.Errorf("模型 %q 不是受支持的 Gemini / Claude / Grok 文本模型", model)
	}
	payload := map[string]any{
		"model":      model,
		"max_tokens": 256,
		"stream":     false,
		"messages": []map[string]any{{
			"role":    "user",
			"content": "Reply with exactly: " + smokeExpectedOutput,
		}},
	}
	body, errJSON := json.Marshal(payload)
	if errJSON != nil {
		return errJSON
	}
	request, errRequest := http.NewRequest(http.MethodPost, a.gatewayURL(current.Port)+"/v1/messages", bytes.NewReader(body))
	if errRequest != nil {
		return errRequest
	}
	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("x-api-key", a.apiKey)
	request.Header.Set("Authorization", "Bearer "+a.apiKey)
	request.Header.Set("anthropic-version", "2023-06-01")
	request.Header.Set("User-Agent", "ZCode-Antigravity-Bridge/"+version)
	response, errDo := httpClient(90 * time.Second).Do(request)
	if errDo != nil {
		return fmt.Errorf("真实模型请求失败: %w", errDo)
	}
	defer response.Body.Close()
	responseBody, errRead := io.ReadAll(io.LimitReader(response.Body, 8<<20))
	if errRead != nil {
		return errRead
	}
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("真实模型请求返回 HTTP %d: %s", response.StatusCode, compactText(responseBody, 600))
	}
	var decoded struct {
		ID      string `json:"id"`
		Model   string `json:"model"`
		Content []struct {
			Type string `json:"type"`
			Text string `json:"text"`
		} `json:"content"`
	}
	if err := json.Unmarshal(responseBody, &decoded); err != nil {
		return fmt.Errorf("真实模型响应不是 Anthropic JSON: %w", err)
	}
	parts := make([]string, 0, len(decoded.Content))
	for _, content := range decoded.Content {
		if content.Type == "text" && strings.TrimSpace(content.Text) != "" {
			parts = append(parts, strings.TrimSpace(content.Text))
		}
	}
	output := strings.Join(parts, "\n")
	if output == "" {
		return fmt.Errorf("真实模型响应没有文本内容")
	}
	if output != smokeExpectedOutput {
		return fmt.Errorf("真实模型响应未通过精确输出校验: %q", compactText([]byte(output), 200))
	}
	audit := smokeAudit{
		Timestamp:      a.now().UTC(),
		RequestedModel: model,
		ResponseModel:  decoded.Model,
		ResponseID:     decoded.ID,
		OutputText:     output,
	}
	auditRaw, errAudit := json.MarshalIndent(audit, "", "  ")
	if errAudit != nil {
		return errAudit
	}
	auditRaw = append(auditRaw, '\n')
	auditPath := filepath.Join(a.paths.Data, "last-smoke-test.json")
	if err := writeAtomic(auditPath, auditRaw, 0o600); err != nil {
		return fmt.Errorf("保存冒烟测试审计: %w", err)
	}
	fmt.Printf("真实模型请求成功: requested=%s response=%s id=%s\n", model, decoded.Model, decoded.ID)
	fmt.Printf("模型输出: %s\n", output)
	fmt.Printf("审计文件: %s\n", auditPath)
	return nil
}

func (a *app) doctor() error {
	cfg := a.currentSettings()
	problems := make([]string, 0)
	if info, err := os.Stat(a.paths.Backend); err != nil {
		problems = append(problems, "缺少 backend/"+filepath.Base(a.paths.Backend))
	} else if info.IsDir() || info.Size() < 1<<20 {
		problems = append(problems, "网关二进制大小异常")
	} else {
		fmt.Printf("[OK] 网关二进制: %s (%d bytes)\n", a.paths.Backend, info.Size())
	}
	if raw, err := os.ReadFile(a.paths.ZCodeConfig); err != nil {
		problems = append(problems, "找不到 ZCode 配置；请先安装并运行一次 ZCode")
	} else {
		var parsed map[string]any
		if json.Unmarshal(raw, &parsed) != nil {
			problems = append(problems, "ZCode config.json 已损坏，程序不会覆盖它")
		} else {
			fmt.Printf("[OK] ZCode 配置: %s\n", a.paths.ZCodeConfig)
		}
	}
	proxyURL, source := a.resolveProxy()
	if proxyURL == "" {
		fmt.Println("[OK] 网络出口: 直连（未发现可用 v2rayN / 系统代理，无需 TUN）。")
	} else {
		fmt.Printf("[OK] 网络出口: %s · %s（无需 TUN）\n", source, redactURLUserinfo(proxyURL))
	}
	if isPortFree(cfg.PreferredPort) {
		fmt.Printf("[OK] 默认 API 端口 %d 当前可用\n", cfg.PreferredPort)
	} else {
		fmt.Printf("[INFO] 默认 API 端口 %d 已占用，启动时会自动换端口 (%s)\n", cfg.PreferredPort, describePortOwner(cfg.PreferredPort))
	}
	if len(problems) > 0 {
		for _, problem := range problems {
			fmt.Printf("[ERROR] %s\n", problem)
		}
		return fmt.Errorf("发现 %d 个问题", len(problems))
	}
	fmt.Println("本机静态检查通过。")
	return nil
}

func redactURLUserinfo(value string) string {
	u, err := urlParse(value)
	if err != nil || u.User == nil {
		return value
	}
	u.User = urlUser("***")
	return u.String()
}

// Indirections keep the redaction helper easy to test without exposing credentials.
var (
	urlParse = func(value string) (*url.URL, error) { return url.Parse(value) }
	urlUser  = url.User
)

func (a *app) stop() error {
	current, err := a.loadState()
	if err != nil {
		return err
	}
	if current.PID <= 0 {
		return fmt.Errorf("没有本程序记录的网关 PID；为避免误杀其他进程，不会按端口强制停止")
	}
	if current.Port <= 0 || a.probeGateway(current.Port) != nil {
		return fmt.Errorf("记录的 PID/端口无法通过网关身份校验；为避免 PID 重用误杀，不会停止")
	}
	expected := current.BackendPath
	if expected == "" {
		expected = a.paths.Backend
	}
	if err := terminateOwnedProcess(current.PID, expected); err != nil {
		return err
	}
	deadline := time.Now().Add(8 * time.Second)
	for time.Now().Before(deadline) {
		if a.probeGateway(current.Port) != nil {
			break
		}
		time.Sleep(200 * time.Millisecond)
	}
	if a.probeGateway(current.Port) == nil {
		return fmt.Errorf("进程已请求停止，但端口仍由兼容网关占用")
	}
	current.PID = 0
	if err := a.saveState(current); err != nil {
		return err
	}
	fmt.Printf("网关已停止，保留端口 %d 供下次启动复用。\n", current.Port)
	return nil
}

